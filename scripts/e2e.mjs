// End-to-end walk of the real app. node scripts/e2e.mjs "<prompt>" <level> <w> <h> [base]
import { chromium } from 'playwright';
const [prompt = 'trigonometry', level = 'Novice', w = '390', h = '844', base = 'http://localhost:3311'] = process.argv.slice(2);
const tag = `${prompt.replace(/\W+/g, '_').slice(0, 30)}-${w}`;
const browser = await chromium.launch({ executablePath: process.env.HOME + '/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: +w, height: +h }, deviceScaleFactor: 2, isMobile: +w < 700, hasTouch: +w < 700 });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push('pageerror: ' + e.message));
page.on('console', (m) => m.type() === 'error' && !/Download the React DevTools|unmount a root/.test(m.text()) && errs.push('console: ' + m.text().slice(0, 200)));
const t0 = Date.now();
const shot = async (n) => { await page.screenshot({ path: `scripts/shots/e2e-${tag}-${n}.png` }); };
await page.goto(base);
await shot('0-home');
await page.getByRole('radio', { name: new RegExp(level) }).click();
await page.locator('#prompt').fill(prompt);
await page.keyboard.press('Enter');
await page.waitForTimeout(400);
await shot('1-planning');
await page.getByText(/Lesson 1 of/).waitFor({ timeout: 60000 });
const tPlan = Date.now() - t0;
await shot('2-course-loading');
await page.getByRole('button', { name: 'Next', exact: true }).waitFor({ timeout: 90000 });
const tLesson = Date.now() - t0;
await page.waitForTimeout(1500);
await shot('3-lesson');
await page.getByRole('button', { name: 'Next', exact: true }).click();
await page.waitForTimeout(1200);
await shot('4-beat2');
await page.locator('#prompt').fill('wait, why does that happen?');
await page.keyboard.press('Enter');
await page.getByText('Back to the lesson').waitFor({ timeout: 45000 });
const tAsk = Date.now() - t0;
await page.waitForTimeout(900);
await shot('5-answer');
await page.getByText('Back to the lesson').click();
await page.getByRole('button', { name: 'All lessons' }).first().click();
await page.waitForTimeout(600);
await shot('6-sheet');
console.log(JSON.stringify({ tag, planMs: tPlan, firstLessonMs: tLesson, askDoneMs: tAsk, errors: errs }));
await browser.close();
