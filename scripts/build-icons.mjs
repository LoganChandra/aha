// Extract a curated set of Lucide icons (ISC licence) into src/lib/icons.ts, so the app ships ~120 icons, not 2,000.
import { writeFileSync } from 'node:fs';
import lucide from 'lucide';
const NAMES = `user users baby hand brain heart eye ear smile
sun moon cloud cloud-rain snowflake droplet droplets leaf tree-deciduous tree-pine flower sprout mountain waves wind flame zap thermometer rainbow
bird fish bug cat dog rabbit
atom dna microscope flask-conical magnet battery battery-charging plug lightbulb cpu radio wifi satellite rocket orbit telescope sigma
syringe pill shield shield-check activity stethoscope bone
coins banknote piggy-bank wallet credit-card landmark store shopping-cart package truck factory scale trending-up trending-down
house building car bike plane ship train-front fuel gauge cog wrench hammer key lock clock hourglass calendar
book book-open graduation-cap pencil music camera smartphone laptop monitor server database globe map-pin flag crown swords scroll gavel
message-circle mail send star target timer apple wheat cookie utensils recycle trash-2 sparkles bot search file-text image ruler
arrow-right arrow-up circle-check circle-x triangle-alert`.split(/\s+/).filter(Boolean);
const pascal = (n) => n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const out = {};
const missing = [];
for (const n of NAMES) {
  const node = lucide.icons[pascal(n)];
  if (!node) { missing.push(n); continue; }
  out[n] = node.map(([tag, attrs]) => [tag, attrs]);
}
writeFileSync('src/lib/icons.ts', `// Generated by scripts/build-icons.mjs from Lucide ${'v1.63.0'} (ISC licence, https://lucide.dev). Do not edit by hand.\n// Each icon is drawn on a 24x24 grid with a 2px round stroke.\nexport type IconNode = [string, Record<string, string>][];\nexport const ICONS: Record<string, IconNode> = ${JSON.stringify(out)};\nexport const ICON_NAMES = Object.keys(ICONS);\n`);
console.log('icons', Object.keys(out).length, 'missing', missing.join(' '));
